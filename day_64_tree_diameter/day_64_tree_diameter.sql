-- ---------------------------------------------------------------------
-- 11. Longest path through each node
-- ---------------------------------------------------------------------

SELECT
    n.node_id,
    n.node_label,
    longest_path_through_node(n.tree_id, n.node_id)
        AS longest_path_through_node_edges
FROM tree_node n
WHERE n.tree_id = 100
ORDER BY n.node_id;

-- The longest value among all node-centered paths must equal
-- the tree diameter.
WITH node_path_metrics AS (
    SELECT
        n.tree_id,
        n.node_id,
        longest_path_through_node(n.tree_id, n.node_id) AS path_edges
    FROM tree_node n
    WHERE n.tree_id = 100
)
SELECT
    max(path_edges) AS diameter_from_node_metrics,
    (SELECT d.diameter_edges
     FROM tree_diameter_report d
     WHERE d.tree_id = 100) AS diameter_from_two_sweeps
FROM node_path_metrics;

-- ---------------------------------------------------------------------
-- 12. Aggregation and eligibility reporting
-- ---------------------------------------------------------------------

SELECT
    count(*) AS validated_tree_count,
    max(diameter_edges) AS maximum_diameter_edges,
    avg(height_edges)::NUMERIC(10, 2) AS average_height_edges,
    avg(diameter_edges)::NUMERIC(10, 2) AS average_diameter_edges
FROM tree_diameter_report;

-- A tree is eligible for diameter reporting only when it is validated.
SELECT
    r.tree_id,
    r.tree_name,
    CASE
        WHEN r.validation_status = 'VALIDATED'
             AND NOT EXISTS (
                 SELECT 1
                 FROM validate_tree(r.tree_id)
             )
        THEN 'ELIGIBLE'
        ELSE 'NOT_ELIGIBLE'
    END AS reporting_eligibility
FROM tree_registry r
ORDER BY r.tree_id;

