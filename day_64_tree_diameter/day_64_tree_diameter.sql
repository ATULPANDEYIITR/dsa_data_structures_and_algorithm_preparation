-- Tree Diameter Practice Project
-- PostgreSQL implementation
--
-- Models hierarchical trees using an adjacency-list representation.
-- Implements tree validation, rooted height, longest path through a node,
-- and diameter using two BFS-style recursive traversals.
--
-- Distances are measured in edges.
-- Run this script in a database where the tree_diameter_lab schema
-- does not already exist.

CREATE SCHEMA tree_diameter_lab;

SET search_path TO tree_diameter_lab, public;

-- ---------------------------------------------------------------------
-- 1. Core relational model
-- ---------------------------------------------------------------------

CREATE TABLE tree_registry (
    tree_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tree_name TEXT NOT NULL CHECK (btrim(tree_name) <> ''),
    validation_status TEXT NOT NULL DEFAULT 'DRAFT'
        CHECK (validation_status IN ('DRAFT', 'VALIDATED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    validated_at TIMESTAMPTZ,

    CHECK (
        (validation_status = 'DRAFT' AND validated_at IS NULL)
        OR
        (validation_status = 'VALIDATED' AND validated_at IS NOT NULL)
    )
);

CREATE TABLE tree_node (
    node_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tree_id BIGINT NOT NULL
        REFERENCES tree_registry(tree_id) ON DELETE CASCADE,
    parent_node_id BIGINT,
    node_label TEXT NOT NULL CHECK (btrim(node_label) <> ''),

    UNIQUE (tree_id, node_id),

    -- The composite foreign key prevents a parent from belonging
    -- to a different tree.
    FOREIGN KEY (tree_id, parent_node_id)
        REFERENCES tree_node(tree_id, node_id)
        DEFERRABLE INITIALLY IMMEDIATE,

    CHECK (
        parent_node_id IS NULL
        OR parent_node_id <> node_id
    )
);

CREATE INDEX idx_tree_node_parent
    ON tree_node(tree_id, parent_node_id)
    WHERE parent_node_id IS NOT NULL;

CREATE INDEX idx_tree_node_tree
    ON tree_node(tree_id);

-- ---------------------------------------------------------------------
-- 2. Mutation and cycle controls
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION prevent_tree_cycles()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = tree_diameter_lab, public
AS $$
DECLARE
    v_cycle_exists BOOLEAN;
BEGIN
    IF NEW.parent_node_id IS NULL THEN
        RETURN NEW;
    END IF;

    -- Follow the prospective parent's ancestors. If the modified node
    -- appears in that chain, the new relationship creates a cycle.
    WITH RECURSIVE ancestors(node_id, parent_node_id, path) AS (
        SELECT
            n.node_id,
            n.parent_node_id,
            ARRAY[n.node_id]::BIGINT[]
        FROM tree_node n
        WHERE n.tree_id = NEW.tree_id
          AND n.node_id = NEW.parent_node_id

        UNION ALL

        SELECT
            p.node_id,
            p.parent_node_id,
            a.path || p.node_id
        FROM ancestors a
        JOIN tree_node p
          ON p.tree_id = NEW.tree_id
         AND p.node_id = a.parent_node_id
        WHERE NOT p.node_id = ANY(a.path)
    )
    SELECT EXISTS (
        SELECT 1
        FROM ancestors
        WHERE node_id = NEW.node_id
    )
    INTO v_cycle_exists;

    IF v_cycle_exists THEN
        RAISE EXCEPTION
            'The parent assignment would create a cycle in tree %',
            NEW.tree_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_prevent_tree_cycles
BEFORE INSERT OR UPDATE OF tree_id, parent_node_id
ON tree_node
FOR EACH ROW
EXECUTE FUNCTION prevent_tree_cycles();


CREATE OR REPLACE FUNCTION guard_validated_tree_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = tree_diameter_lab, public
AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        IF EXISTS (
            SELECT 1
            FROM tree_registry r
            WHERE r.tree_id = OLD.tree_id
              AND r.validation_status = 'VALIDATED'
        ) THEN
            RAISE EXCEPTION
                'Validated tree % cannot be modified',
                OLD.tree_id;
        END IF;
    END IF;

    IF TG_OP <> 'DELETE' THEN
        IF EXISTS (
            SELECT 1
            FROM tree_registry r
            WHERE r.tree_id = NEW.tree_id
              AND r.validation_status = 'VALIDATED'
        ) THEN
            RAISE EXCEPTION
                'Validated tree % cannot be modified',
                NEW.tree_id;
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_validated_tree_mutation
BEFORE INSERT OR UPDATE OR DELETE
ON tree_node
FOR EACH ROW
EXECUTE FUNCTION guard_validated_tree_mutation();

-- ---------------------------------------------------------------------
-- 3. Tree validation
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION validate_tree(p_tree_id BIGINT)
RETURNS TABLE (
    issue_code TEXT,
    detail TEXT
)
LANGUAGE plpgsql
STABLE
SET search_path = tree_diameter_lab, public
AS $$
DECLARE
    v_node_count BIGINT;
    v_root_count BIGINT;
    v_root_id BIGINT;
    v_reachable_count BIGINT;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM tree_registry r
        WHERE r.tree_id = p_tree_id
    ) THEN
        RETURN QUERY
        SELECT
            'TREE_NOT_FOUND'::TEXT,
            format('Tree %s does not exist.', p_tree_id);
        RETURN;
    END IF;

    SELECT
        count(*),
        count(*) FILTER (WHERE n.parent_node_id IS NULL)
    INTO v_node_count, v_root_count
    FROM tree_node n
    WHERE n.tree_id = p_tree_id;

    IF v_node_count = 0 THEN
        RETURN QUERY
        SELECT
            'EMPTY_TREE'::TEXT,
            'A tree must contain at least one node.';
        RETURN;
    END IF;

    IF v_root_count <> 1 THEN
        RETURN QUERY
        SELECT
            'ROOT_COUNT'::TEXT,
            format(
                'Expected exactly one root; found %s.',
                v_root_count
            );
        RETURN;
    END IF;

    SELECT n.node_id
    INTO v_root_id
    FROM tree_node n
    WHERE n.tree_id = p_tree_id
      AND n.parent_node_id IS NULL;

    -- UNION removes repeated node IDs. This also prevents an invalid
    -- cyclic component from causing an unbounded recursive traversal.
    WITH RECURSIVE reachable(node_id) AS (
        SELECT v_root_id

        UNION

        SELECT child.node_id
        FROM tree_node child
        JOIN reachable r
          ON child.parent_node_id = r.node_id
        WHERE child.tree_id = p_tree_id
    )
    SELECT count(*)
    INTO v_reachable_count
    FROM reachable;

    IF v_reachable_count <> v_node_count THEN
        RETURN QUERY
        SELECT
            'UNREACHABLE_NODES'::TEXT,
            format(
                '%s of %s nodes cannot be reached from the root.',
                v_node_count - v_reachable_count,
                v_node_count
            );
        RETURN;
    END IF;

    RETURN;
END;
$$;

CREATE OR REPLACE PROCEDURE mark_tree_validated(p_tree_id BIGINT)
LANGUAGE plpgsql
SET search_path = tree_diameter_lab, public
AS $$
DECLARE
    v_issues TEXT;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM tree_registry r
        WHERE r.tree_id = p_tree_id
    ) THEN
        RAISE EXCEPTION 'Tree % does not exist.', p_tree_id;
    END IF;

    SELECT string_agg(
        v.issue_code || ': ' || v.detail,
        '; '
    )
    INTO v_issues
    FROM validate_tree(p_tree_id) v;

    IF v_issues IS NOT NULL THEN
        RAISE EXCEPTION
            'Tree % cannot be validated: %',
            p_tree_id,
            v_issues;
    END IF;

    UPDATE tree_registry
    SET validation_status = 'VALIDATED',
        validated_at = clock_timestamp()
    WHERE tree_id = p_tree_id
      AND validation_status = 'DRAFT';
END;
$$;

-- ---------------------------------------------------------------------
-- 4. Farthest-node traversal
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION farthest_tree_node(
    p_tree_id BIGINT,
    p_start_node_id BIGINT
)
RETURNS TABLE (
    node_id BIGINT,
    distance INTEGER
)
LANGUAGE plpgsql
STABLE
SET search_path = tree_diameter_lab, public
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM tree_node n
        WHERE n.tree_id = p_tree_id
          AND n.node_id = p_start_node_id
    ) THEN
        RAISE EXCEPTION
            'Starting node % does not belong to tree %',
            p_start_node_id,
            p_tree_id;
    END IF;

    RETURN QUERY
    WITH RECURSIVE adjacency(node_id, neighbor_id) AS (
        SELECT n.parent_node_id, n.node_id
        FROM tree_node n
        WHERE n.tree_id = p_tree_id
          AND n.parent_node_id IS NOT NULL

        UNION ALL

        SELECT n.node_id, n.parent_node_id
        FROM tree_node n
        WHERE n.tree_id = p_tree_id
          AND n.parent_node_id IS NOT NULL
    ),
    walk(current_node_id, current_distance, visited_path) AS (
        SELECT
            p_start_node_id,
            0,
            ARRAY[p_start_node_id]::BIGINT[]

        UNION ALL

        SELECT
            a.neighbor_id,
            w.current_distance + 1,
            w.visited_path || a.neighbor_id
        FROM walk w
        JOIN adjacency a
          ON a.node_id = w.current_node_id
        WHERE NOT a.neighbor_id = ANY(w.visited_path)
    )
    SELECT
        w.current_node_id,
        w.current_distance
    FROM walk w
    ORDER BY w.current_distance DESC, w.current_node_id
    LIMIT 1;
END;
$$;

-- ---------------------------------------------------------------------
-- 5. Tree height and diameter using two traversals
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION compute_tree_diameter(p_tree_id BIGINT)
RETURNS TABLE (
    tree_id BIGINT,
    root_node_id BIGINT,
    height_edges INTEGER,
    diameter_edges INTEGER,
    diameter_nodes INTEGER,
    endpoint_a BIGINT,
    endpoint_b BIGINT
)
LANGUAGE plpgsql
STABLE
SET search_path = tree_diameter_lab, public
AS $$
DECLARE
    v_issues TEXT;
    v_root_id BIGINT;
    v_endpoint_a BIGINT;
    v_endpoint_b BIGINT;
    v_height INTEGER;
    v_diameter INTEGER;
BEGIN
    SELECT string_agg(
        v.issue_code || ': ' || v.detail,
        '; '
    )
    INTO v_issues
    FROM validate_tree(p_tree_id) v;

    IF v_issues IS NOT NULL THEN
        RAISE EXCEPTION
            'Cannot calculate diameter for tree %: %',
            p_tree_id,
            v_issues;
    END IF;

    SELECT n.node_id
    INTO v_root_id
    FROM tree_node n
    WHERE n.tree_id = p_tree_id
      AND n.parent_node_id IS NULL;

    -- First traversal: root to a farthest node.
    SELECT f.node_id, f.distance
    INTO v_endpoint_a, v_height
    FROM farthest_tree_node(p_tree_id, v_root_id) f;

    -- Second traversal: endpoint A to the opposite diameter endpoint.
    SELECT f.node_id, f.distance
    INTO v_endpoint_b, v_diameter
    FROM farthest_tree_node(p_tree_id, v_endpoint_a) f;

    RETURN QUERY
    SELECT
        p_tree_id,
        v_root_id,
        v_height,
        v_diameter,
        v_diameter + 1,
        v_endpoint_a,
        v_endpoint_b;
END;
$$;

-- ---------------------------------------------------------------------
-- 6. Longest path through a selected node
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION longest_path_through_node(
    p_tree_id BIGINT,
    p_node_id BIGINT
)
RETURNS INTEGER
LANGUAGE plpgsql
STABLE
SET search_path = tree_diameter_lab, public
AS $$
DECLARE
    v_issues TEXT;
    v_result INTEGER;
BEGIN
    SELECT string_agg(
        v.issue_code || ': ' || v.detail,
        '; '
    )
    INTO v_issues
    FROM validate_tree(p_tree_id) v;

    IF v_issues IS NOT NULL THEN
        RAISE EXCEPTION
            'Cannot inspect tree %: %',
            p_tree_id,
            v_issues;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM tree_node n
        WHERE n.tree_id = p_tree_id
          AND n.node_id = p_node_id
    ) THEN
        RAISE EXCEPTION
            'Node % does not belong to tree %',
            p_node_id,
            p_tree_id;
    END IF;

    -- Start one traversal for every neighbor of the selected node.
    -- Each traversal remains inside that neighbor's component after
    -- the selected node is removed.
    WITH RECURSIVE adjacency(node_id, neighbor_id) AS (
        SELECT n.parent_node_id, n.node_id
        FROM tree_node n
        WHERE n.tree_id = p_tree_id
          AND n.parent_node_id IS NOT NULL

        UNION ALL

        SELECT n.node_id, n.parent_node_id
        FROM tree_node n
        WHERE n.tree_id = p_tree_id
          AND n.parent_node_id IS NOT NULL
    ),
    walk(first_neighbor, current_node_id, current_distance, visited_path) AS (
        SELECT
            a.neighbor_id,
            a.neighbor_id,
            1,
            ARRAY[p_node_id, a.neighbor_id]::BIGINT[]
        FROM adjacency a
        WHERE a.node_id = p_node_id

        UNION ALL

        SELECT
            w.first_neighbor,
            a.neighbor_id,
            w.current_distance + 1,
            w.visited_path || a.neighbor_id
        FROM walk w
        JOIN adjacency a
          ON a.node_id = w.current_node_id
        WHERE NOT a.neighbor_id = ANY(w.visited_path)
    ),
    branch_heights AS (
        SELECT
            first_neighbor,
            max(current_distance) AS branch_height
        FROM walk
        GROUP BY first_neighbor
    ),
    ranked_branches AS (
        SELECT
            branch_height,
            row_number() OVER (
                ORDER BY branch_height DESC, first_neighbor
            ) AS branch_rank
        FROM branch_heights
    )
    SELECT COALESCE(sum(branch_height), 0)::INTEGER
    INTO v_result
    FROM ranked_branches
    WHERE branch_rank <= 2;

    RETURN v_result;
END;
$$;

-- ---------------------------------------------------------------------
-- 7. Reporting views
-- ---------------------------------------------------------------------

CREATE VIEW tree_node_structure AS
SELECT
    n.tree_id,
    n.node_id,
    n.parent_node_id,
    n.node_label,
    count(child.node_id)::INTEGER AS child_count,
    (count(child.node_id) = 0) AS is_leaf
FROM tree_node n
LEFT JOIN tree_node child
  ON child.tree_id = n.tree_id
 AND child.parent_node_id = n.node_id
GROUP BY
    n.tree_id,
    n.node_id,
    n.parent_node_id,
    n.node_label;

CREATE VIEW tree_node_depth AS
WITH RECURSIVE node_depths(
    tree_id,
    node_id,
    parent_node_id,
    depth_edges
) AS (
    SELECT
        n.tree_id,
        n.node_id,
        n.parent_node_id,
        0
    FROM tree_node n
    WHERE n.parent_node_id IS NULL

    UNION ALL

    SELECT
        child.tree_id,
        child.node_id,
        child.parent_node_id,
        parent.depth_edges + 1
    FROM tree_node child
    JOIN node_depths parent
      ON parent.tree_id = child.tree_id
     AND parent.node_id = child.parent_node_id
)
SELECT
    tree_id,
    node_id,
    parent_node_id,
    depth_edges
FROM node_depths;

CREATE VIEW tree_diameter_report AS
SELECT
    r.tree_id,
    r.tree_name,
    d.root_node_id,
    d.height_edges,
    d.diameter_edges,
    d.diameter_nodes,
    d.endpoint_a,
    d.endpoint_b,
    r.validated_at
FROM (
    SELECT *
    FROM tree_registry
    WHERE validation_status = 'VALIDATED'
) r
CROSS JOIN LATERAL compute_tree_diameter(r.tree_id) d;

