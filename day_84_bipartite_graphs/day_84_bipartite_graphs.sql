-- ------------------------------------------------------------
-- 16. Transactional graph modification
--
-- Adding edge (0,2) to the even cycle creates a triangle.
-- The transaction can be rolled back without changing the
-- permanent graph state.
-- ------------------------------------------------------------

SAVEPOINT before_conflict_test;

INSERT INTO graph_edge (graph_id, vertex_a, vertex_b)
VALUES (1, 0, 2)
ON CONFLICT DO NOTHING;

SELECT evaluate_assignment(1, 1) AS conflicting_graph_decision;

ROLLBACK TO SAVEPOINT before_conflict_test;

-- ------------------------------------------------------------
-- 17. Integrity validation
-- ------------------------------------------------------------

SELECT
    e.graph_id,
    e.vertex_a,
    e.vertex_b
FROM graph_edge e
LEFT JOIN graph_vertex a
    ON a.graph_id = e.graph_id
   AND a.vertex_id = e.vertex_a
LEFT JOIN graph_vertex b
    ON b.graph_id = e.graph_id
   AND b.vertex_id = e.vertex_b
WHERE a.vertex_id IS NULL
   OR b.vertex_id IS NULL;

COMMIT;
