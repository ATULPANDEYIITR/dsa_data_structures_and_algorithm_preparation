-- ------------------------------------------------------------
-- 8. Execute analysis and policy evaluation transactionally
-- ------------------------------------------------------------

DO $$
DECLARE
    v_graph_id BIGINT;
BEGIN
    FOR v_graph_id IN
        SELECT graph_id
        FROM graph
        ORDER BY graph_id
    LOOP
        PERFORM evaluate_assignment(v_graph_id, 1);
    END LOOP;
END;
$$;

-- ------------------------------------------------------------
-- 9. Retrieval
-- ------------------------------------------------------------

SELECT *
FROM bipartite_graph_report
ORDER BY graph_id;

-- ------------------------------------------------------------
-- 10. Retrieve individual color assignments
-- ------------------------------------------------------------

SELECT
    g.graph_name,
    a.analysis_id,
    v.vertex_id,
    v.vertex_name,
    CASE vc.color
        WHEN 0 THEN 'RED'
        WHEN 1 THEN 'BLUE'
    END AS assigned_color,
    vc.component_id
FROM vertex_coloring vc
JOIN graph_analysis a
    ON a.analysis_id = vc.analysis_id
JOIN graph g
    ON g.graph_id = vc.graph_id
JOIN graph_vertex v
    ON v.graph_id = vc.graph_id
   AND v.vertex_id = vc.vertex_id
WHERE a.is_bipartite
ORDER BY g.graph_id, vc.component_id, v.vertex_id;

-- ------------------------------------------------------------
-- 11. Validation and conflict retrieval
-- ------------------------------------------------------------

SELECT
    g.graph_name,
    a.is_bipartite,
    a.conflicting_vertex_a,
    a.conflicting_vertex_b,
    CASE
        WHEN a.is_bipartite THEN 'VALID'
        ELSE 'INVALID'
    END AS validation_status
FROM graph_analysis a
JOIN graph g
    ON g.graph_id = a.graph_id
ORDER BY a.analysis_id;

-- ------------------------------------------------------------
-- 12. Aggregation
-- ------------------------------------------------------------

SELECT
    graph_id,
    COUNT(*) AS analyzed_graphs,
    COUNT(*) FILTER (WHERE is_bipartite) AS valid_analyses,
    COUNT(*) FILTER (WHERE NOT is_bipartite) AS invalid_analyses
FROM graph_analysis
GROUP BY graph_id
ORDER BY graph_id;

-- ------------------------------------------------------------
-- 13. Policy eligibility report
-- ------------------------------------------------------------

SELECT
    g.graph_name,
    p.policy_name,
    d.eligible,
    d.decision_reason,
    d.decided_at
FROM assignment_decision d
JOIN graph g
    ON g.graph_id = d.graph_id
JOIN assignment_policy p
    ON p.policy_id = d.policy_id
ORDER BY d.decision_id;

-- ------------------------------------------------------------
-- 14. CTE: latest eligible decisions
-- ------------------------------------------------------------

WITH ranked_decisions AS (
    SELECT
        d.*,
        ROW_NUMBER() OVER (
            PARTITION BY d.graph_id, d.policy_id
            ORDER BY d.decided_at DESC, d.decision_id DESC
        ) AS position
    FROM assignment_decision d
)
SELECT
    g.graph_name,
    p.policy_name,
    rd.eligible,
    rd.decision_reason
FROM ranked_decisions rd
JOIN graph g ON g.graph_id = rd.graph_id
JOIN assignment_policy p ON p.policy_id = rd.policy_id
WHERE rd.position = 1;

