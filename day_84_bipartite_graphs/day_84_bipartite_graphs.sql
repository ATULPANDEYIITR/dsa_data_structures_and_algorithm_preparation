-- ============================================================
-- BIPARTITE GRAPHS: TWO-COLORING AND GRAPH VALIDATION
-- PostgreSQL implementation
--
-- Domain:
-- Departments are vertices.
-- Incompatible department pairs are undirected edges.
-- Two groups represent the two available assignment categories.
--
-- Implements:
-- 1. Graph and edge storage.
-- 2. BFS-based two-coloring using recursive SQL.
-- 3. Connected component tracking.
-- 4. Bipartite condition validation.
-- 5. Conflict and odd-cycle detection.
-- 6. Assignment eligibility.
-- 7. Constraints, triggers, indexes, and reporting.
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS graph_lab;

SET search_path TO graph_lab, public;

-- ------------------------------------------------------------
-- 1. Domain tables
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS graph (
    graph_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    graph_name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT graph_name_nonempty
        CHECK (length(trim(graph_name)) > 0)
);

CREATE TABLE IF NOT EXISTS graph_vertex (
    graph_id BIGINT NOT NULL
        REFERENCES graph(graph_id) ON DELETE CASCADE,
    vertex_id INTEGER NOT NULL,
    vertex_name VARCHAR(120) NOT NULL,
    vertex_type VARCHAR(50) NOT NULL DEFAULT 'GENERAL',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (graph_id, vertex_id),

    CONSTRAINT vertex_id_nonnegative
        CHECK (vertex_id >= 0),

    CONSTRAINT vertex_name_nonempty
        CHECK (length(trim(vertex_name)) > 0)
);

CREATE TABLE IF NOT EXISTS graph_edge (
    edge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    graph_id BIGINT NOT NULL,

    vertex_a INTEGER NOT NULL,
    vertex_b INTEGER NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (graph_id, vertex_a)
        REFERENCES graph_vertex(graph_id, vertex_id)
        ON DELETE CASCADE,

    FOREIGN KEY (graph_id, vertex_b)
        REFERENCES graph_vertex(graph_id, vertex_id)
        ON DELETE CASCADE,

    CONSTRAINT canonical_edge_order
        CHECK (vertex_a <= vertex_b),

    CONSTRAINT unique_undirected_edge
        UNIQUE (graph_id, vertex_a, vertex_b)
);

CREATE TABLE IF NOT EXISTS graph_analysis (
    analysis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    graph_id BIGINT NOT NULL
        REFERENCES graph(graph_id) ON DELETE CASCADE,

    algorithm VARCHAR(10) NOT NULL,

    is_bipartite BOOLEAN NOT NULL,

    component_count INTEGER NOT NULL DEFAULT 0,

    conflicting_vertex_a INTEGER,
    conflicting_vertex_b INTEGER,

    analyzed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_algorithm
        CHECK (algorithm IN ('BFS', 'DFS')),

    CONSTRAINT valid_component_count
        CHECK (component_count >= 0)
);

CREATE TABLE IF NOT EXISTS vertex_coloring (
    analysis_id BIGINT NOT NULL
        REFERENCES graph_analysis(analysis_id) ON DELETE CASCADE,

    graph_id BIGINT NOT NULL,

    vertex_id INTEGER NOT NULL,

    color SMALLINT NOT NULL,

    component_id INTEGER NOT NULL,

    PRIMARY KEY (analysis_id, vertex_id),

    FOREIGN KEY (graph_id, vertex_id)
        REFERENCES graph_vertex(graph_id, vertex_id),

    CONSTRAINT valid_color
        CHECK (color IN (0, 1)),

    CONSTRAINT valid_component
        CHECK (component_id >= 0)
);

CREATE TABLE IF NOT EXISTS assignment_policy (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    policy_name VARCHAR(120) NOT NULL UNIQUE,

    required_groups INTEGER NOT NULL DEFAULT 2,

    enabled BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT valid_required_groups
        CHECK (required_groups >= 1)
);

CREATE TABLE IF NOT EXISTS assignment_decision (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    graph_id BIGINT NOT NULL
        REFERENCES graph(graph_id) ON DELETE CASCADE,

    policy_id BIGINT NOT NULL
        REFERENCES assignment_policy(policy_id),

    analysis_id BIGINT
        REFERENCES graph_analysis(analysis_id),

    eligible BOOLEAN NOT NULL,

    decision_reason TEXT NOT NULL,

    decided_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

