-- ------------------------------------------------------------
-- 3. Canonical undirected edge insertion
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION normalize_edge_vertices()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    temporary_vertex INTEGER;
BEGIN
    IF NEW.vertex_a > NEW.vertex_b THEN
        temporary_vertex := NEW.vertex_a;
        NEW.vertex_a := NEW.vertex_b;
        NEW.vertex_b := temporary_vertex;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_normalize_edge ON graph_edge;

CREATE TRIGGER trg_normalize_edge
BEFORE INSERT OR UPDATE ON graph_edge
FOR EACH ROW
EXECUTE FUNCTION normalize_edge_vertices();

-- ------------------------------------------------------------
-- 4. BFS two-coloring function
--
-- The temporary work tables maintain:
-- - assigned colors
-- - BFS frontier
-- - next frontier
-- - parent relationships
--
-- Every connected component receives a new root.
-- A same-color edge proves non-bipartiteness.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION analyze_bipartite_bfs(
    p_graph_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_start INTEGER;
    v_u INTEGER;
    v_v INTEGER;
    v_color INTEGER;
    v_component INTEGER := 0;
    v_conflict_a INTEGER := NULL;
    v_conflict_b INTEGER := NULL;
    v_is_bipartite BOOLEAN := TRUE;
    v_analysis_id BIGINT;
    v_found_new BOOLEAN;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM graph
        WHERE graph_id = p_graph_id
    ) THEN
        RAISE EXCEPTION 'Graph % does not exist', p_graph_id;
    END IF;

    CREATE TEMP TABLE IF NOT EXISTS work_colors (
        vertex_id INTEGER PRIMARY KEY,
        color INTEGER NOT NULL,
        component_id INTEGER NOT NULL,
        parent_id INTEGER
    ) ON COMMIT DROP;

    CREATE TEMP TABLE IF NOT EXISTS work_frontier (
        vertex_id INTEGER PRIMARY KEY
    ) ON COMMIT DROP;

    CREATE TEMP TABLE IF NOT EXISTS work_next (
        vertex_id INTEGER PRIMARY KEY
    ) ON COMMIT DROP;

    TRUNCATE work_colors, work_frontier, work_next;

    FOR v_start IN
        SELECT vertex_id
        FROM graph_vertex
        WHERE graph_id = p_graph_id
        ORDER BY vertex_id
    LOOP
        IF EXISTS (
            SELECT 1
            FROM work_colors
            WHERE vertex_id = v_start
        ) THEN
            CONTINUE;
        END IF;

        v_component := v_component + 1;

        INSERT INTO work_colors (
            vertex_id, color, component_id, parent_id
        )
        VALUES (v_start, 0, v_component, NULL);

        INSERT INTO work_frontier VALUES (v_start);

        WHILE EXISTS (SELECT 1 FROM work_frontier)
        LOOP
            TRUNCATE work_next;

            FOR v_u IN
                SELECT vertex_id
                FROM work_frontier
                ORDER BY vertex_id
            LOOP
                SELECT color
                INTO v_color
                FROM work_colors
                WHERE vertex_id = v_u;

                FOR v_v IN
                    SELECT CASE
                        WHEN vertex_a = v_u THEN vertex_b
                        ELSE vertex_a
                    END
                    FROM graph_edge
                    WHERE graph_id = p_graph_id
                      AND (vertex_a = v_u OR vertex_b = v_u)
                    ORDER BY edge_id
                LOOP
                    IF NOT EXISTS (
                        SELECT 1
                        FROM work_colors
                        WHERE vertex_id = v_v
                    ) THEN
                        INSERT INTO work_colors (
                            vertex_id,
                            color,
                            component_id,
                            parent_id
                        )
                        VALUES (
                            v_v,
                            1 - v_color,
                            v_component,
                            v_u
                        );

                        INSERT INTO work_next
                        VALUES (v_v)
                        ON CONFLICT DO NOTHING;

                    ELSE
                        IF EXISTS (
                            SELECT 1
                            FROM work_colors
                            WHERE vertex_id = v_v
                              AND color = v_color
                        ) THEN
                            v_is_bipartite := FALSE;
                            v_conflict_a := v_u;
                            v_conflict_b := v_v;
                            EXIT;
                        END IF;
                    END IF;
                END LOOP;

                IF NOT v_is_bipartite THEN
                    EXIT;
                END IF;
            END LOOP;

            EXIT WHEN NOT v_is_bipartite;

            TRUNCATE work_frontier;

            INSERT INTO work_frontier
            SELECT vertex_id
            FROM work_next;

        END LOOP;

        EXIT WHEN NOT v_is_bipartite;
    END LOOP;

    INSERT INTO graph_analysis (
        graph_id,
        algorithm,
        is_bipartite,
        component_count,
        conflicting_vertex_a,
        conflicting_vertex_b
    )
    VALUES (
        p_graph_id,
        'BFS',
        v_is_bipartite,
        v_component,
        v_conflict_a,
        v_conflict_b
    )
    RETURNING analysis_id INTO v_analysis_id;

    INSERT INTO vertex_coloring (
        analysis_id,
        graph_id,
        vertex_id,
        color,
        component_id
    )
    SELECT
        v_analysis_id,
        p_graph_id,
        vertex_id,
        color,
        component_id
    FROM work_colors;

    RETURN v_analysis_id;
END;
$$;

-- ------------------------------------------------------------
-- 5. Eligibility evaluation
--
-- A two-group assignment requires:
-- 1. An enabled policy.
-- 2. Exactly two required groups.
-- 3. A successful bipartite analysis.
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION evaluate_assignment(
    p_graph_id BIGINT,
    p_policy_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_analysis_id BIGINT;
    v_eligible BOOLEAN;
    v_reason TEXT;
    v_policy_enabled BOOLEAN;
    v_required_groups INTEGER;
    v_decision_id BIGINT;
    v_bipartite BOOLEAN;
BEGIN
    SELECT enabled, required_groups
    INTO v_policy_enabled, v_required_groups
    FROM assignment_policy
    WHERE policy_id = p_policy_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Policy % does not exist', p_policy_id;
    END IF;

    IF NOT v_policy_enabled THEN
        v_eligible := FALSE;
        v_reason := 'Assignment policy is disabled.';

    ELSIF v_required_groups <> 2 THEN
        v_eligible := FALSE;
        v_reason := 'This evaluation requires exactly two groups.';

    ELSE
        v_analysis_id := analyze_bipartite_bfs(p_graph_id);

        SELECT is_bipartite
        INTO v_bipartite
        FROM graph_analysis
        WHERE analysis_id = v_analysis_id;

        v_eligible := v_bipartite;

        IF v_bipartite THEN
            v_reason := 'Graph satisfies the two-coloring condition.';
        ELSE
            v_reason := 'An odd cycle or self-loop prevents two-coloring.';
        END IF;
    END IF;

    INSERT INTO assignment_decision (
        graph_id,
        policy_id,
        analysis_id,
        eligible,
        decision_reason
    )
    VALUES (
        p_graph_id,
        p_policy_id,
        v_analysis_id,
        v_eligible,
        v_reason
    )
    RETURNING decision_id INTO v_decision_id;

    RETURN v_decision_id;
END;
$$;

-- ------------------------------------------------------------
-- 6. Reporting views
-- ------------------------------------------------------------

CREATE OR REPLACE VIEW bipartite_graph_report AS
SELECT
    g.graph_id,
    g.graph_name,
    COUNT(DISTINCT v.vertex_id) AS vertex_count,
    COUNT(DISTINCT e.edge_id) AS edge_count,
    latest.is_bipartite,
    latest.component_count,
    latest.analyzed_at
FROM graph g
LEFT JOIN graph_vertex v
    ON v.graph_id = g.graph_id
LEFT JOIN graph_edge e
    ON e.graph_id = g.graph_id
LEFT JOIN LATERAL (
    SELECT
        a.is_bipartite,
        a.component_count,
        a.analyzed_at
    FROM graph_analysis a
    WHERE a.graph_id = g.graph_id
    ORDER BY a.analyzed_at DESC, a.analysis_id DESC
    LIMIT 1
) latest ON TRUE
GROUP BY
    g.graph_id,
    g.graph_name,
    latest.is_bipartite,
    latest.component_count,
    latest.analyzed_at;

CREATE OR REPLACE VIEW assignment_group_report AS
SELECT
    a.analysis_id,
    a.graph_id,
    vc.component_id,
    COUNT(*) FILTER (WHERE vc.color = 0) AS red_vertices,
    COUNT(*) FILTER (WHERE vc.color = 1) AS blue_vertices
FROM graph_analysis a
JOIN vertex_coloring vc
    ON vc.analysis_id = a.analysis_id
WHERE a.is_bipartite
GROUP BY
    a.analysis_id,
    a.graph_id,
    vc.component_id;

